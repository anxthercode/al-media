from __future__ import annotations

from PySide6.QtCore import QSize, Qt
from PySide6.QtWidgets import QFrame, QHBoxLayout, QLabel, QLineEdit, QProgressBar, QVBoxLayout, QWidget

from .composer_options import ComposerOptions, OptionsPopup
from .media_preview import MediaPreview, SourceLayout
from .selection import FormatPicker
from .widgets import DisclosureButton


def downloads_page(window):
    page, layout = window._page()
    window.format_picker = FormatPicker(window.preferences)
    window.format_picker.changed.connect(window._composer_selection)
    composer = QFrame()
    composer.setObjectName("composer")
    content = QVBoxLayout(composer)
    content.setContentsMargins(0, 0, 0, 0)
    content.setSpacing(0)
    content.addWidget(window._label("link", "fieldCaption"))
    content.addSpacing(8)
    window.input = QLineEdit()
    window.input.setAcceptDrops(False)
    window.input.setPlaceholderText("https://…")
    window.input.setFixedHeight(38)
    content.addWidget(window.input)
    window.analysis_bar = QProgressBar()
    window.analysis_bar.setFixedHeight(3)
    window.analysis_bar.setRange(0, 0)
    window.analysis_bar.setTextVisible(False)
    window.analysis_bar.hide()
    content.addWidget(window.analysis_bar)
    window.analysis_status = window._label("fetching_metadata", "fieldCaption")
    window.analysis_status.hide()
    content.addWidget(window.analysis_status)
    content.addSpacing(14)
    window.empty_hint = window._label("insert_link_hint", "muted")
    window.empty_hint.setAlignment(Qt.AlignmentFlag.AlignCenter)
    window.empty_hint.setMinimumHeight(180)
    content.addWidget(window.empty_hint)
    window.loading_panel = QWidget()
    loading = QHBoxLayout(window.loading_panel)
    loading.setContentsMargins(0, 0, 0, 0)
    loading.setSpacing(20)
    skeleton = QVBoxLayout()
    skeleton.setSpacing(16)
    skeleton.addStretch()
    for width, height in ((170, 12), (260, 22), (190, 12)):
        bar = QFrame()
        bar.setObjectName("skeleton")
        bar.setFixedSize(width, height)
        skeleton.addWidget(bar)
    skeleton.addStretch()
    loading.addLayout(skeleton, 1)
    preview_hint = window._label("getting_preview", "loadingPreview")
    preview_hint.setAlignment(Qt.AlignmentFlag.AlignCenter)
    preview_hint.setFixedHeight(200)
    loading.addWidget(preview_hint, 1)
    content.addWidget(window.loading_panel)
    window.loading_panel.hide()
    information = QWidget()
    fields = QVBoxLayout(information)
    fields.setContentsMargins(0, 0, 0, 0)
    fields.setSpacing(0)
    window.source_panel = QWidget()
    details = QVBoxLayout(window.source_panel)
    details.setContentsMargins(0, 0, 0, 0)
    details.setSpacing(0)
    source_row = QHBoxLayout()
    source_row.setSpacing(8)
    window.source_icon = QLabel()
    window.source_icon.setFixedSize(22, 22)
    window.source_name = window._label("", "muted")
    source_row.addWidget(window.source_icon)
    source_row.addWidget(window.source_name, 1)
    details.addLayout(source_row)
    details.addSpacing(8)
    window.source_title = QLabel()
    window.source_title.setObjectName("sourceTitle")
    window.source_title.setTextFormat(Qt.TextFormat.PlainText)
    window.source_title.setWordWrap(True)
    window.source_title.setMinimumWidth(0)
    window.source_title.setMaximumHeight(46)
    details.addWidget(window.source_title)
    details.addSpacing(10)
    window.source_details = QLabel()
    window.source_details.setObjectName("muted")
    window.source_details.setTextFormat(Qt.TextFormat.PlainText)
    window.source_details.setWordWrap(True)
    window.source_details.setMaximumHeight(34)
    details.addWidget(window.source_details)
    details.addSpacing(14)
    facts = QHBoxLayout()
    facts.setSpacing(24)
    window.source_duration, window.source_size = QLabel(), QLabel()
    for key, label in (("duration", window.source_duration), ("estimated_size", window.source_size)):
        column = QVBoxLayout()
        column.setSpacing(7)
        column.addWidget(window._label(key, "fieldCaption"))
        label.setTextFormat(Qt.TextFormat.PlainText)
        label.setObjectName("sourceFact")
        column.addWidget(label)
        facts.addLayout(column)
    facts.addStretch(1)
    details.addLayout(facts)
    window.source_panel.hide()
    fields.addWidget(window.source_panel)
    fields.addStretch(1)
    fields.addSpacing(14)
    fields.addWidget(window.format_picker.modes)
    window.media_preview = MediaPreview(window.images, window.preferences, window.windowIcon(), tools=window.scheduler.tools)
    window.media_preview.hide()
    window.source_layout = SourceLayout(information, window.media_preview)
    content.addWidget(window.source_layout)
    window.source_layout.hide()
    window.format_picker.modes.hide()
    content.addSpacing(16)
    window.parameter_fields = QWidget()
    parameters = QHBoxLayout(window.parameter_fields)
    parameters.setContentsMargins(0, 0, 0, 0)
    parameters.setSpacing(20)
    parameters.addWidget(window.format_picker, 1)
    advanced = QWidget()
    advanced_column = QVBoxLayout(advanced)
    advanced_column.setContentsMargins(0, 0, 0, 0)
    advanced_column.setSpacing(8)
    window.advanced_caption = window._label("fragment_tracks", "fieldCaption")
    advanced_column.addWidget(window.advanced_caption)
    window.preview_advanced = DisclosureButton()
    window.preview_advanced.toggled.connect(window._preview_options)
    advanced_column.addWidget(window.preview_advanced)
    parameters.addWidget(advanced, 1)
    parameters.setAlignment(window.format_picker, Qt.AlignmentFlag.AlignBottom)
    content.addWidget(window.parameter_fields)
    window.parameter_fields.hide()
    window.options_popup = OptionsPopup(window.preview_advanced, window)
    window.options_editor = ComposerOptions(window.preferences)
    window.options_popup.content.addWidget(window.options_editor)
    window.options_popup.closed.connect(window._dismiss_preview_options)
    window.options_editor.accepted.connect(window._apply_preview_options)
    window.input_error = QLabel()
    window.input_error.setTextFormat(Qt.TextFormat.PlainText)
    window.input_error.setObjectName("error")
    window.input_error.setWordWrap(True)
    window.input_error.hide()
    content.addWidget(window.input_error)
    actions = QHBoxLayout()
    actions.setContentsMargins(0, 20, 0, 4)
    actions.addStretch(1)
    window.add_button = window._button("download_now", window._add_urls, primary=True, icon="download")
    window.add_button.setObjectName("downloadPrimary")
    window.add_button.setFixedSize(240, 42)
    window.add_button.setIconSize(QSize(18, 18))
    window.add_button.hide()
    actions.addWidget(window.add_button)
    actions.addStretch(1)
    content.addLayout(actions)
    layout.addWidget(composer)
    window.active_panel = QWidget()
    active = QVBoxLayout(window.active_panel)
    active.setContentsMargins(0, 4, 0, 0)
    active.setSpacing(12)
    heading = QHBoxLayout()
    heading.addWidget(window._label("active_queue", "sectionTitle"), 1)
    window.queue_summary = window._label("", "fieldCaption")
    window.queue_summary.setWordWrap(False)
    heading.addWidget(window.queue_summary)
    window.all_button = window._button("all", window._download_all, icon="download")
    window.stop_button = window._button("stop_all", window._stop_all, icon="cancel")
    for button in (window.all_button, window.stop_button):
        button.setObjectName("rowAction")
        button.setFixedSize(32, 32)
    heading.addWidget(window.all_button)
    heading.addWidget(window.stop_button)
    active.addLayout(heading)
    window.active_layout = QVBoxLayout()
    window.active_layout.setContentsMargins(0, 0, 0, 0)
    window.active_layout.setSpacing(4)
    active.addLayout(window.active_layout)
    layout.addWidget(window.active_panel)
    window.completed_panel = QWidget()
    completed = QVBoxLayout(window.completed_panel)
    completed.setContentsMargins(0, 4, 0, 0)
    completed.setSpacing(16)
    line = QFrame()
    line.setObjectName("separator")
    completed.addWidget(line)
    heading = QHBoxLayout()
    heading.addWidget(window._label("downloaded_files", "sectionTitle"), 1)
    window.clear_button = window._button("clear_list", window._clear_completed, icon="listClear")
    window.clear_button.setObjectName("quiet")
    heading.addWidget(window.clear_button)
    completed.addLayout(heading)
    window.cards_layout = QVBoxLayout()
    window.cards_layout.setContentsMargins(0, 0, 0, 0)
    window.cards_layout.setSpacing(10)
    completed.addLayout(window.cards_layout)
    layout.addWidget(window.completed_panel)
    layout.addStretch(1)
    window.add_button.setEnabled(False)
    for previous, following in zip((window.input, window.format_picker.video, window.format_picker.audio, window.format_picker.quality,
                                    window.format_picker.audio_format, window.format_picker.bitrate, window.preview_advanced),
                                   (window.format_picker.video, window.format_picker.audio, window.format_picker.quality,
                                    window.format_picker.audio_format, window.format_picker.bitrate, window.preview_advanced, window.add_button), strict=True):
        QWidget.setTabOrder(previous, following)
    return page
